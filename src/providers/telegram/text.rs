//! Text chunking and tool-call tag stripping for Telegram.

use crate::channel::LengthUnit;
use crate::text::{ChunkMode, TextChunkOptions, chunk_text_with_options};

/// Telegram's maximum message length for text messages
pub(crate) const TELEGRAM_MAX_MESSAGE_LENGTH: usize = 4096;
pub(crate) const TELEGRAM_BIND_COMMAND: &str = "/bind";
pub(crate) const TELEGRAM_START_COMMAND: &str = "/start";

pub(crate) fn split_message_for_telegram(message: &str) -> Vec<String> {
    if message.is_empty() {
        return vec![String::new()];
    }
    chunk_text_with_options(
        message,
        TextChunkOptions {
            limit: TELEGRAM_MAX_MESSAGE_LENGTH,
            length_unit: LengthUnit::Utf16Units,
            mode: ChunkMode::Length,
            markdown: true,
            indicators: false,
        },
    )
}

/// Escape literal MarkdownV2 control characters while retaining balanced
/// Telegram emphasis, spoiler, and code delimiters generated by the model.
pub(crate) fn markdown_v2_text(message: &str) -> String {
    const SPECIAL: &str = "\\_*[]()~`>#+-=|{}.!";
    let chars = message.chars().collect::<Vec<_>>();
    let mut syntax = vec![false; chars.len()];
    let mut code = vec![false; chars.len()];
    let mut url = vec![false; chars.len()];
    let mut escaped = vec![false; chars.len()];
    let mut slash_run = 0;
    for (index, ch) in chars.iter().enumerate() {
        escaped[index] = slash_run % 2 == 1;
        slash_run = if *ch == '\\' { slash_run + 1 } else { 0 };
    }

    // Pair inline and fenced code delimiters in one pass. Code spans have
    // their own escaping rules and are opaque to the later syntax scans.
    let mut code_open: Option<(usize, usize)> = None;
    let mut cursor = 0;
    while cursor < chars.len() {
        if chars[cursor] != '`' || escaped[cursor] {
            cursor += 1;
            continue;
        }
        let start = cursor;
        while chars.get(cursor) == Some(&'`') {
            cursor += 1;
        }
        let run = cursor - start;
        let width = if run >= 3 { 3 } else { 1 };
        match code_open {
            Some((open, open_width)) if width == open_width => {
                syntax[open..open + open_width].fill(true);
                syntax[start..start + open_width].fill(true);
                code[open + open_width..start].fill(true);
                code_open = None;
            }
            Some(_) => {
                // Other backtick runs are code content, not nested entities.
            }
            None => code_open = Some((start, width)),
        }
    }

    // Precompute bracket and parenthesis pairs once so link syntax and URL
    // escaping are identified before emphasis delimiters are considered.
    let mut bracket_stack = Vec::new();
    let mut bracket_pairs = vec![None; chars.len()];
    let mut nested_bracket = vec![false; chars.len()];
    let mut paren_stack = Vec::new();
    let mut paren_pairs = vec![None; chars.len()];
    for index in 0..chars.len() {
        if code[index] || escaped[index] {
            continue;
        }
        match chars[index] {
            '[' => bracket_stack.push(index),
            ']' => {
                if let Some(open) = bracket_stack.pop() {
                    bracket_pairs[open] = Some(index);
                    bracket_pairs[index] = Some(open);
                    if let Some(parent) = bracket_stack.last() {
                        nested_bracket[*parent] = true;
                    }
                }
            }
            '(' => paren_stack.push(index),
            ')' => {
                if let Some(open) = paren_stack.pop() {
                    paren_pairs[open] = Some(index);
                    paren_pairs[index] = Some(open);
                }
            }
            _ => {}
        }
    }
    let mut last_url_end = 0;
    for open in 0..chars.len() {
        let Some(close) = bracket_pairs[open] else {
            continue;
        };
        if chars[open] != '[' || nested_bracket[open] || chars.get(close + 1) != Some(&'(') {
            continue;
        }
        let url_open = close + 1;
        let Some(url_close) = paren_pairs[url_open] else {
            continue;
        };
        if url_open <= last_url_end {
            continue;
        }
        syntax[open] = true;
        syntax[close] = true;
        syntax[url_open] = true;
        syntax[url_close] = true;
        url[url_open + 1..url_close].fill(true);
        last_url_end = url_close;
    }

    // Preserve only balanced emphasis/spoiler delimiters. Unclosed markers
    // become escaped literal text rather than invalid Telegram markup.
    let mut open_tokens = Vec::<(char, usize)>::new();
    cursor = 0;
    while cursor < chars.len() {
        if code[cursor] || url[cursor] || escaped[cursor] {
            cursor += 1;
            continue;
        }
        let token = if chars[cursor] == '|' && chars.get(cursor + 1) == Some(&'|') {
            Some(('|', 2))
        } else if matches!(chars[cursor], '*' | '_' | '~') {
            Some((chars[cursor], 1))
        } else {
            None
        };
        let Some((token, width)) = token else {
            cursor += 1;
            continue;
        };
        if open_tokens.last().is_some_and(|(open, _)| *open == token) {
            let (_, open) = open_tokens.pop().expect("last token exists");
            syntax[open..open + width].fill(true);
            syntax[cursor..cursor + width].fill(true);
        } else if open_tokens.iter().any(|(open, _)| *open == token) {
            // Crossing markup is invalid in MarkdownV2. Leave all involved
            // delimiters literal instead of emitting a malformed entity.
            open_tokens.clear();
        } else {
            open_tokens.push((token, cursor));
        }
        cursor += width;
    }

    let mut output = String::with_capacity(message.len() + message.len() / 8);
    cursor = 0;
    while cursor < chars.len() {
        let ch = chars[cursor];
        if syntax[cursor] {
            output.push(ch);
        } else if code[cursor] {
            if ch == '\\'
                && chars
                    .get(cursor + 1)
                    .is_some_and(|next| matches!(next, '\\' | '`'))
            {
                output.push(ch);
                cursor += 1;
                output.push(chars[cursor]);
            } else {
                if matches!(ch, '\\' | '`') {
                    output.push('\\');
                }
                output.push(ch);
            }
        } else if ch == '\\'
            && chars
                .get(cursor + 1)
                .is_some_and(|next| SPECIAL.contains(*next))
        {
            output.push(ch);
            cursor += 1;
            output.push(chars[cursor]);
        } else if url[cursor] {
            if matches!(ch, '\\' | ')') {
                output.push('\\');
            }
            output.push(ch);
        } else if ch == '>' && (cursor == 0 || chars[cursor - 1] == '\n') {
            output.push(ch);
        } else if SPECIAL.contains(ch) {
            output.push('\\');
            output.push(ch);
        } else {
            output.push(ch);
        }
        cursor += 1;
    }
    output
}

pub(crate) fn strip_tool_call_tags(message: &str) -> String {
    const TOOL_CALL_OPEN_TAGS: [&str; 5] = [
        "<tool_call>",
        "<toolcall>",
        "<tool-call>",
        "<tool>",
        "<invoke>",
    ];

    fn find_first_tag<'a>(haystack: &str, tags: &'a [&'a str]) -> Option<(usize, &'a str)> {
        tags.iter()
            .filter_map(|tag| haystack.find(tag).map(|idx| (idx, *tag)))
            .min_by_key(|(idx, _)| *idx)
    }

    fn matching_close_tag(open_tag: &str) -> Option<&'static str> {
        match open_tag {
            "<tool_call>" => Some("</tool_call>"),
            "<toolcall>" => Some("</toolcall>"),
            "<tool-call>" => Some("</tool-call>"),
            "<tool>" => Some("</tool>"),
            "<invoke>" => Some("</invoke>"),
            _ => None,
        }
    }

    fn extract_first_json_end(input: &str) -> Option<usize> {
        let trimmed = input.trim_start();
        let trim_offset = input.len().saturating_sub(trimmed.len());

        for (byte_idx, ch) in trimmed.char_indices() {
            if ch != '{' && ch != '[' {
                continue;
            }

            let slice = &trimmed[byte_idx..];
            let mut stream =
                serde_json::Deserializer::from_str(slice).into_iter::<serde_json::Value>();
            if let Some(Ok(_value)) = stream.next() {
                let consumed = stream.byte_offset();
                if consumed > 0 {
                    return Some(trim_offset + byte_idx + consumed);
                }
            }
        }

        None
    }

    fn strip_leading_close_tags(mut input: &str) -> &str {
        loop {
            let trimmed = input.trim_start();
            if !trimmed.starts_with("</") {
                return trimmed;
            }

            let Some(close_end) = trimmed.find('>') else {
                return "";
            };
            input = &trimmed[close_end + 1..];
        }
    }

    let mut kept_segments = Vec::new();
    let mut remaining = message;

    while let Some((start, open_tag)) = find_first_tag(remaining, &TOOL_CALL_OPEN_TAGS) {
        let before = &remaining[..start];
        if !before.is_empty() {
            kept_segments.push(before.to_string());
        }

        let Some(close_tag) = matching_close_tag(open_tag) else {
            break;
        };
        let after_open = &remaining[start + open_tag.len()..];

        if let Some(close_idx) = after_open.find(close_tag) {
            remaining = &after_open[close_idx + close_tag.len()..];
            continue;
        }

        if let Some(consumed_end) = extract_first_json_end(after_open) {
            remaining = strip_leading_close_tags(&after_open[consumed_end..]);
            continue;
        }

        kept_segments.push(remaining[start..].to_string());
        remaining = "";
        break;
    }

    if !remaining.is_empty() {
        kept_segments.push(remaining.to_string());
    }

    let mut result = kept_segments.concat();

    // Clean up any resulting blank lines (but preserve paragraphs)
    while result.contains("\n\n\n") {
        result = result.replace("\n\n\n", "\n\n");
    }

    result.trim().to_string()
}

